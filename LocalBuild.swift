    private func checkEnvironment(force: Bool, buildAfterCheck: Bool) {
        let checkID = UUID()
        environmentCheckID = checkID
        environmentReady = false
        verifiedImageID = nil
        isRunning = true
        statusText = "กำลังตรวจ Environment"
        statusColor = .blue

        environmentTask = Task { [weak self] in
            guard let self else { return }
            do {
                try self.validateStorage()
                if buildAfterCheck { await self.prepareNotifications() }
                try Task.checkCancellation()
                let startedAt = ProcessInfo.processInfo.systemUptime
                guard let dockerPath = self.dockerPath else {
                    throw NSError(domain: "LocalBuild", code: 1, userInfo: [
                        NSLocalizedDescriptionKey: "ไม่พบ Docker CLI กรุณาเปิดหรือติดตั้ง Docker Desktop"
                    ])
                }
                if force { LocalEnvironmentCache.clear(defaults: self.defaults) }
                self.appendLog("\n===== Local Environment Check =====\n")
                self.statusText = "กำลังตรวจ Docker Engine"
                let engineOutput = try await self.runTool(
                    executable: dockerPath,
                    arguments: ["info", "--format", "ENGINE_ID={{.ID}}"],
                    errorMessage: "Docker Engine ไม่พร้อม กรุณาเปิด Docker Desktop"
                )
                guard let engineLine = engineOutput.components(separatedBy: .newlines)
                    .first(where: { $0.hasPrefix("ENGINE_ID=") }),
                      !engineLine.dropFirst(10).isEmpty else {
                    throw NSError(domain: "LocalBuild", code: 2, userInfo: [
                        NSLocalizedDescriptionKey: "อ่าน Docker Engine ID ไม่สำเร็จ"
                    ])
                }
                self.statusText = "กำลังตรวจ Vivado image"
                let imageOutput = try await self.runTool(
                    executable: dockerPath,
                    arguments: ["image", "inspect", self.configuredDockerImage,
                                "--format", "IMAGE={{.Os}}/{{.Architecture}} {{.Id}}"],
                    errorMessage: "ไม่พบ image \(self.configuredDockerImage)"
                )
                let imageLine = imageOutput.components(separatedBy: .newlines)
                    .first(where: { $0.hasPrefix("IMAGE=") }) ?? ""
                let imageFields = imageLine.dropFirst(6).split(whereSeparator: { $0.isWhitespace })
                guard imageFields.count == 2, imageFields[0] == "linux/amd64",
                      imageFields[1].hasPrefix("sha256:") else {
                    throw NSError(domain: "LocalBuild", code: 3, userInfo: [
                        NSLocalizedDescriptionKey: "Vivado image ต้องเป็น linux/amd64 และมี image ID"
                    ])
                }
                let signature = LocalEnvironmentSignature(
                    engineID: String(engineLine.dropFirst(10)),
                    imageID: String(imageFields[1]),
                    settingsPath: self.configuredVivadoSettingsPath,
                    part: LocalBuildTemplates.part
                )
                if !force && LocalEnvironmentCache.matches(signature, defaults: self.defaults) {
                    self.appendLog("✓ ใช้ผลตรวจ Vivado เดิม\n")
                } else {
                    self.statusText = "กำลังตรวจ Vivado และ FPGA part"
                    let command = LocalBuildTemplates.vivadoCommand(
                        settingsPath: signature.settingsPath,
                        command: "echo 'if {[llength [get_parts \(signature.part)]] != 1} {exit 2}; puts {LOCAL_ENV_PASS}; exit' > /tmp/local-check.tcl && vivado -mode batch -nolog -nojournal -notrace -source /tmp/local-check.tcl"
                    )
                    let partOutput = try await self.runTool(
                        executable: dockerPath,
                        arguments: [
                            "run", "--rm", "--pull=never", "--platform", "linux/amd64",
                            "--network", "none", signature.imageID, "/bin/bash", "-lc", command
                        ],
                        errorMessage: "ตรวจ Vivado หรือ FPGA part \(signature.part) ไม่ผ่าน"
                    )
                    guard partOutput.contains("LOCAL_ENV_PASS") else {
                        throw NSError(domain: "LocalBuild", code: 4, userInfo: [
                            NSLocalizedDescriptionKey: "Vivado ไม่ยืนยันผลตรวจ FPGA part"
                        ])
                    }
                    try LocalEnvironmentCache.save(signature, defaults: self.defaults)
                    self.appendLog("✓ บันทึกผลตรวจ Vivado แล้ว\n")
                }
                try Task.checkCancellation()
                guard self.environmentCheckID == checkID else { return }
                self.verifiedImageID = signature.imageID
                self.environmentReady = true
                self.appendLog(String(format: "ตรวจ Environment: %.2f วินาที\n",
                                      ProcessInfo.processInfo.systemUptime - startedAt))
                if buildAfterCheck {
                    try self.validateStorage()
                    let job = try self.prepareJob()
                    self.environmentCheckID = nil
                    self.environmentTask = nil
                    self.runBuild(job)
                } else {
                    self.environmentCheckID = nil
                    self.environmentTask = nil
                    self.isRunning = false
                    self.statusText = "Local Vivado พร้อม Build"
                    self.statusColor = .green
                }
            } catch {
                guard self.environmentCheckID == checkID else { return }
                self.environmentCheckID = nil
                self.environmentTask = nil
                self.isRunning = false
                self.environmentReady = false
                self.verifiedImageID = nil
                self.fail(error.localizedDescription)
                if buildAfterCheck {
                    self.notifyBuild(succeeded: false, top: self.topEntity,
                                     message: error.localizedDescription, destination: nil)
                }
            }
        }
    }

    private func prepareNotifications() async {
        guard notificationsEnabled else { return }
        do {
            let granted = try await BuildNotifications.shared.requestAuthorizationIfNeeded()
            if !granted && !reportedNotificationDenial {
                reportedNotificationDenial = true
                appendLog("แจ้งเตือนปิดอยู่ เปิดได้ใน System Settings > Notifications\n")
            }
        } catch {
            appendLog("ขอสิทธิ์แจ้งเตือนไม่สำเร็จ: \(error.localizedDescription)\n")
        }
    }

    private func notifyBuild(succeeded: Bool, top: String, message: String, destination: URL?) {
        guard notificationsEnabled else { return }
        let sound = notificationSoundEnabled
        Task {
            do {
                try await BuildNotifications.shared.send(
                    topEntity: top, succeeded: succeeded, message: message,
                    destination: destination, sound: sound
                )
            } catch {
                appendLog("ส่งแจ้งเตือนไม่สำเร็จ: \(error.localizedDescription)\n")
            }
        }
    }

    func cancel() {
        guard isRunning else { return }
        appendLog("\nกำลังหยุด Local Build…\n")
        if let environmentTask {
            environmentCheckID = nil
            self.environmentTask = nil
            environmentTask.cancel()
            currentProcess?.terminate()
            currentProcess = nil
            isRunning = false
            statusText = "ยกเลิกการตรวจ Environment แล้ว"
            statusColor = .orange
            return
        }
        buildWasCancelled = true
        if let containerName = activeContainerName, let dockerPath {
            let stop = Process()
            stop.executableURL = URL(fileURLWithPath: dockerPath)
            stop.arguments = ["stop", "--time", "10", containerName]
            try? stop.run()
        } else if let currentProcess, currentProcess.isRunning {
            currentProcess.terminate()
        }
        statusText = "กำลังยกเลิก"
        statusColor = .orange
    }

    func revealResult() {
        guard let resultFolder else { return }
        NSWorkspace.shared.activateFileViewerSelecting([resultFolder])
    }

    func clearLog() {
        uiLog.clear()
    }

    func saveMappingState() {
        persistCurrentMapping()
    }

    private struct PreparedJob {
        let jobID: String
        let topEntity: String
        let imageID: String
        let sourceURL: URL
        let resultURL: URL
        let sourceNames: [String]
        let buildTclURL: URL
