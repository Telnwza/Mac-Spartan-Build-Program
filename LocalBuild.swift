    func savePreset(named name: String) {
        guard let snapshot = currentSnapshot(), !name.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            return
        }
        let preset = PinMappingStore.savePreset(name: name, snapshot: snapshot)
        mappingPresets = PinMappingStore.presets(profileID: preset.profileID)
        mappingNotice = "บันทึก Preset ‘\(preset.name)’ แล้ว"
    }

    func applyPreset(_ preset: PinMappingPreset) {
        guard let profile else { return }
        let merged = PinMappingEngine.merge(
            ports: ports,
            current: [:],
            saved: preset.mapping,
            automatic: autoMappings(for: ports),
            validPins: Set(profile.pins.keys)
        )
        selectedPins = merged.mapping
        if ports.contains(where: { $0.caseInsensitiveCompare(preset.clockSignal) == .orderedSame }),
           let clock = ports.first(where: { $0.caseInsensitiveCompare(preset.clockSignal) == .orderedSame }) {
            clockSignal = clock
            clockPeriod = preset.clockPeriod
        }
        mappingNotice = "ใช้ Preset ‘\(preset.name)’ • ตรงกัน \(merged.reusedCount)/\(ports.count) signals"
        persistCurrentMapping()
    }

    func deletePreset(_ preset: PinMappingPreset) {
        PinMappingStore.deletePreset(preset)
        mappingPresets = profile.map { PinMappingStore.presets(profileID: $0.profileID) } ?? []
        mappingNotice = "ลบ Preset ‘\(preset.name)’ แล้ว"
    }

    func pinOwners(excluding excludedPorts: Set<String> = []) -> [String: String] {
        var result: [String: String] = [:]
        for port in ports where !excludedPorts.contains(port) {
            if let pin = selectedPins[port], !pin.isEmpty { result[pin] = port }
        }
        return result
    }

