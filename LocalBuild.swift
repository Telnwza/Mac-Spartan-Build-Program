enum LocalConstraintMode: String, CaseIterable, Identifiable {
    case guided
    case existingXDC

    var id: String { rawValue }

    var title: String {
        switch self {
        case .guided: return "สร้าง XDC จาก Pin Mapping"
        case .existingXDC: return "ใช้ไฟล์ XDC ที่มีอยู่"
        }
    }
}

enum LocalBuildTemplates {
    static let part = "xc7s15ftgb196-1"
    static let defaultDockerImage = "xilinx-vivado:2025.2"
    static let defaultVivadoSettingsPath = "/opt/Xilinx/2025.2/Vivado/settings64.sh"
    static let dockerPlatform = "linux/amd64"

    static var usesRosetta: Bool {
        #if arch(arm64)
        return true
        #else
        return false
        #endif
    }

    static func vivadoCommand(settingsPath: String, command: String, rosetta: Bool = usesRosetta) -> String {
        let settings = "'\(settingsPath.replacingOccurrences(of: "'", with: "'\"'\"'"))'"
        // Upstream applies this in run.vivado.sh; the app invokes Docker directly.
        let preload = rosetta
            ? "if [ -f /opt/udev_stub.so ]; then export LD_PRELOAD=\"/opt/udev_stub.so${LD_PRELOAD:+:$LD_PRELOAD}\"; fi; "
            : ""
        return "\(preload)test -f \(settings) && source \(settings) && \(command)"
    }

    static func generatedXDC(
        ports: [String],
        selectedPins: [String: String],
        clockSignal: String,
        periodNS: Double
    ) -> String {
        var lines = [
            "# Generated by Spartan Build & Program",
            "# Target: EDGE Spartan-7 \(part)",
            ""
        ]
        for port in ports {
            guard let pin = selectedPins[port], !pin.isEmpty else { continue }
            lines.append("set_property -dict { PACKAGE_PIN \(pin) IOSTANDARD LVCMOS33 } [get_ports {\(port)}]")
        }
        lines += [
            "",
            String(format: "create_clock -name sys_clk -period %.3f [get_ports {%@}]", periodNS, clockSignal),
            ""
        ]
        return lines.joined(separator: "\n")
    }

    static func buildTcl(sourceNames: [String], topEntity: String) -> String {
        let sources = sourceNames.map { "    read_vhdl -vhdl2008 /src/\($0)" }
            .joined(separator: "\n")
        return """
        # Generated by Spartan Build & Program
        set part \(part)
        set top \(topEntity)

        if {[catch {
        \(sources)
            read_xdc /src/constraints.xdc

            synth_design -top $top -part $part
            write_checkpoint -force /work/post_synth.dcp
            report_utilization -file /work/utilization_synth.rpt

            opt_design
            place_design
            write_checkpoint -force /work/post_place.dcp

            route_design
            write_checkpoint -force /work/post_route.dcp
            report_route_status -file /work/route_status.rpt
            report_timing_summary -delay_type min_max -report_unconstrained -check_timing_verbose -max_paths 10 -input_pins -file /work/timing_summary.rpt
            report_utilization -file /work/utilization.rpt
            check_timing -verbose -file /work/check_timing.rpt

            set versionFile [open /work/vivado-version.txt w]
            puts $versionFile [version]
            close $versionFile

            write_bitstream -force /work/\(topEntity).bit
            puts "BUILD_COMPLETE: /work/\(topEntity).bit"
        } buildError buildOptions]} {
            puts stderr "LOCAL_BUILD_ERROR: $buildError"
            if {[dict exists $buildOptions -errorinfo]} {
                puts stderr [dict get $buildOptions -errorinfo]
            }
            exit 1
        }
        exit 0
        """
    }
}

enum LocalBuildValidation {
    static func routeHasZeroErrors(_ report: String) -> Bool {
        report.range(
            of: #"(?im)#\s+of\s+nets\s+with\s+routing\s+errors\.*\s*:\s*0\s*:"#,
            options: .regularExpression
        ) != nil
    }

    static func resultPassed(log: String, timing: String, route: String, bitURL: URL) -> Bool {
        log.contains("BUILD_COMPLETE:")
            && !log.contains("ERROR:")
            && timing.contains("All user specified timing constraints are met")
            && routeHasZeroErrors(route)
            && BitstreamInspector.detectedBoard(at: bitURL) == .edgeSpartan7
    }
}

struct LocalEnvironmentSignature: Codable, Equatable {
    let engineID: String
    let imageID: String
    let settingsPath: String
    let part: String
}

enum LocalEnvironmentCache {
    private static let key = "localEnvironment.validated.v2"

    static func matches(_ signature: LocalEnvironmentSignature, defaults: UserDefaults) -> Bool {
        guard let data = defaults.data(forKey: key),
              let saved = try? JSONDecoder().decode(LocalEnvironmentSignature.self, from: data) else {
            return false
        }
        return saved == signature
    }

    static func save(_ signature: LocalEnvironmentSignature, defaults: UserDefaults) throws {
        defaults.set(try JSONEncoder().encode(signature), forKey: key)
    }

    static func clear(defaults: UserDefaults) {
        defaults.removeObject(forKey: key)
    }
}

