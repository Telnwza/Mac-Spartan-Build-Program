    func setPin(_ pin: String, for port: String) {
        if !pin.isEmpty {
            for otherPort in ports where otherPort != port && selectedPins[otherPort] == pin {
                selectedPins[otherPort] = ""
            }
            recentPins = PinMappingStore.recordRecentPin(pin)
        }
        selectedPins[port] = pin
        mappingNotice = pin.isEmpty ? "ล้าง Mapping ของ \(port)" : "กำหนด \(port) → \(pin)"
        persistCurrentMapping()
    }

    func togglePortSelection(_ port: String) {
        if selectedPorts.contains(port) {
            selectedPorts.remove(port)
        } else {
            selectedPorts.insert(port)
        }
    }

    func setPortsSelected(_ portNames: [String], selected: Bool) {
        if selected {
            selectedPorts.formUnion(portNames)
        } else {
            selectedPorts.subtract(portNames)
        }
    }

    func clearSelectedMappings() {
        guard !selectedPorts.isEmpty else { return }
        for port in selectedPorts { selectedPins[port] = "" }
        mappingNotice = "ล้าง Mapping \(selectedPorts.count) signals"
        persistCurrentMapping()
    }

    func resetMapping() {
        selectedPins = autoMappings(for: ports)
        selectedPorts.removeAll()
        mappingNotice = "Reset แล้ว • ใช้เฉพาะ Auto Mapping เริ่มต้น"
        persistCurrentMapping()
    }

    func autoMapUnmapped() {
        let targets = Set(ports.filter { (selectedPins[$0] ?? "").isEmpty })
        autoMap(targets: targets)
    }

    func autoMapSelected() {
        autoMap(targets: selectedPorts)
    }

    func assignSelectedSequentially(category: PinCategory, reversed: Bool = false) {
        assignSequentially(ports: selectedPorts, category: category, reversed: reversed)
