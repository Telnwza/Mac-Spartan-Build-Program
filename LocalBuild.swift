    private func validateStorage() throws {
        let cleanedImage = configuredDockerImage
        guard !cleanedImage.isEmpty, !cleanedImage.contains("\n") else {
            throw NSError(domain: "LocalBuild", code: 2, userInfo: [NSLocalizedDescriptionKey: "กรุณาระบุชื่อ Docker image"])
        }
        guard configuredVivadoSettingsPath.hasPrefix("/"), !configuredVivadoSettingsPath.contains("\n") else {
            throw NSError(domain: "LocalBuild", code: 3, userInfo: [NSLocalizedDescriptionKey: "Vivado settings path ต้องเป็น absolute path ภายใน Container"])
        }
        guard let minimumFreeBytes else {
            throw NSError(domain: "LocalBuild", code: 4, userInfo: [NSLocalizedDescriptionKey: "พื้นที่ว่างขั้นต่ำต้องอยู่ระหว่าง 1–1,000 GiB"])
        }
        let rootURL = URL(fileURLWithPath: buildRoot, isDirectory: true).standardizedFileURL
        guard rootURL.path != "/" else {
            throw NSError(domain: "LocalBuild", code: 5, userInfo: [NSLocalizedDescriptionKey: "ไม่อนุญาตให้ใช้ root filesystem เป็นโฟลเดอร์ Build"])
        }
        try FileManager.default.createDirectory(at: rootURL, withIntermediateDirectories: true)
        guard FileManager.default.isWritableFile(atPath: rootURL.path) else {
            throw NSError(domain: "LocalBuild", code: 6, userInfo: [NSLocalizedDescriptionKey: "ไม่มีสิทธิ์เขียนโฟลเดอร์ Build ที่เลือก"])
        }
        let available = try freeBytes(at: rootURL.path)
        guard available >= minimumFreeBytes else {
            throw NSError(domain: "LocalBuild", code: 7, userInfo: [NSLocalizedDescriptionKey: "พื้นที่ว่างน้อยกว่า \(minimumFreeGiB) GiB จึงหยุดอย่างปลอดภัย"])
        }
    }

    private func freeBytes(at path: String) throws -> UInt64 {
        var probe = path
        while !FileManager.default.fileExists(atPath: probe) {
            let parent = URL(fileURLWithPath: probe).deletingLastPathComponent().path
            if parent == probe { break }
            probe = parent
        }
        let attributes = try FileManager.default.attributesOfFileSystem(forPath: probe)
        guard let value = attributes[.systemFreeSize] as? NSNumber else {
            throw NSError(domain: "LocalBuild", code: 8, userInfo: [NSLocalizedDescriptionKey: "อ่านพื้นที่ว่างของโฟลเดอร์ Build ไม่สำเร็จ"])
        }
        return value.uint64Value
    }

    private func currentSnapshot() -> PinMappingSnapshot? {
