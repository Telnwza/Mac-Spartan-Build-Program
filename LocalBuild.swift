enum LocalBuildSelfTest {
    @MainActor
    static func run() -> Bool {
        let suiteName = "LocalBuildSelfTest.\(UUID().uuidString)"
        guard let defaults = UserDefaults(suiteName: suiteName) else { return false }
        defer { defaults.removePersistentDomain(forName: suiteName) }
        defaults.set(false, forKey: "localBuildNotifications")
        let signature = LocalEnvironmentSignature(
            engineID: "engine-1", imageID: "sha256:image-1", settingsPath: "/vivado/settings64.sh",
            part: LocalBuildTemplates.part
        )
        guard !LocalEnvironmentCache.matches(signature, defaults: defaults) else { return false }
        do { try LocalEnvironmentCache.save(signature, defaults: defaults) } catch { return false }
        guard let reopened = UserDefaults(suiteName: suiteName),
              LocalEnvironmentCache.matches(signature, defaults: reopened) else { return false }
        let changedSignatures = [
            LocalEnvironmentSignature(engineID: "engine-2", imageID: signature.imageID,
                                      settingsPath: signature.settingsPath, part: signature.part),
            LocalEnvironmentSignature(engineID: signature.engineID, imageID: "sha256:image-2",
                                      settingsPath: signature.settingsPath, part: signature.part),
            LocalEnvironmentSignature(engineID: signature.engineID, imageID: signature.imageID,
                                      settingsPath: "/other/settings64.sh", part: signature.part),
            LocalEnvironmentSignature(engineID: signature.engineID, imageID: signature.imageID,
                                      settingsPath: signature.settingsPath, part: "other-part")
        ]
        guard changedSignatures.allSatisfy({ !LocalEnvironmentCache.matches($0, defaults: reopened) }) else {
            return false
        }
        LocalEnvironmentCache.clear(defaults: defaults)
        guard !LocalEnvironmentCache.matches(signature, defaults: defaults) else { return false }
        let successNotice = BuildNotifications.content(
            topEntity: "demo", succeeded: true, message: "Timing และ Routing ผ่าน",
            destination: URL(fileURLWithPath: "/tmp/result"), sound: false
        )
        let failureNotice = BuildNotifications.content(
            topEntity: "demo", succeeded: false, message: "Timing ไม่ผ่าน",
            destination: URL(fileURLWithPath: "/tmp/result/build.log"), sound: true
        )
        guard successNotice.title.contains("Build สำเร็จ"), successNotice.sound == nil,
              successNotice.userInfo["resultPath"] as? String == "/tmp/result",
              failureNotice.title.contains("Build ไม่สำเร็จ"), failureNotice.sound != nil,
              failureNotice.userInfo["resultPath"] as? String == "/tmp/result/build.log" else {
            return false
        }

        let expectedSegmentPins = ["L3", "P4", "P2", "M3", "M1", "J4", "K4", "J2"]
        let model = LocalBuildModel(defaults: defaults)
        for width in [7, 8] {
            let segmentPorts = (0..<width).reversed().map { "segment[\($0)]" }
            var expectedMapping = ["led0": "K12"]
            for index in 0..<width {
                expectedMapping["segment[\(index)]"] = expectedSegmentPins[index]
            }
            model.ports = ["led0"] + segmentPorts
            model.selectedPorts = Set(segmentPorts)
            model.selectedPins = ["led0": "K12"]
            for port in segmentPorts { model.selectedPins[port] = "J2" }
            model.autoMapSelected()
            guard model.selectedPins == expectedMapping, model.duplicatePins.isEmpty else {
                return false
            }

            model.selectedPins["segment[\(width - 1)]"] = ""
            model.autoMapUnmapped()
            guard model.selectedPins == expectedMapping else { return false }
        }

        let expectedLEDPins = [
            "K12", "M12", "M14", "P13", "N11", "P11", "L5", "M4",
            "J4", "L3", "P4", "K4", "P2", "J2", "M3", "M1"
        ]
        let ledPorts = (0..<16).reversed().map { "led[\($0)]" }
        var expectedLEDMapping = ["clk": "H11"]
        for index in 0..<16 {
            expectedLEDMapping["led[\(index)]"] = expectedLEDPins[index]
        }
        model.ports = ["clk"] + ledPorts
        model.selectedPorts = Set(ledPorts)
        model.selectedPins = ["clk": "H11"]
        model.autoMapSelected()
        guard model.selectedPins == expectedLEDMapping, model.duplicatePins.isEmpty else {
            return false
        }
        for index in [8, 11, 15] { model.selectedPins["led[\(index)]"] = "" }
        model.autoMapUnmapped()
        guard model.selectedPins == expectedLEDMapping else { return false }

        model.sourceFiles = [URL(fileURLWithPath: "/tmp/demo.vhd")]
        model.topEntity = "demo"
        model.clockSignal = "clk"
        model.environmentReady = false
        guard model.canBuild else { return false }
        model.environmentReady = true
        model.setBuildRoot("/tmp/local-build-test")
        model.setMinimumFreeGiB("1")
        guard model.environmentReady else { return false }
        model.setDockerImage("other-image")
        guard !model.environmentReady else { return false }

        let xdc = LocalBuildTemplates.generatedXDC(
            ports: ["clk", "led"],
            selectedPins: ["clk": "H11", "led": "K12"],
            clockSignal: "clk",
            periodNS: 20
        )
        let tcl = LocalBuildTemplates.buildTcl(
            sourceNames: ["blink_counter.vhd"],
            topEntity: "blink_counter"
        )
        let requiredStages = [
            "read_vhdl", "read_xdc", "synth_design", "opt_design",
            "place_design", "route_design", "report_timing_summary",
            "report_utilization", "write_bitstream"
        ]
        var previous = tcl.startIndex
        let ordered = requiredStages.allSatisfy { stage in
            guard let range = tcl.range(of: stage, range: previous..<tcl.endIndex) else { return false }
            previous = range.upperBound
            return true
        }
        return xdc.contains("PACKAGE_PIN H11")
            && xdc.contains("PACKAGE_PIN K12")
            && xdc.contains("create_clock -name sys_clk -period 20.000")
            && tcl.contains("-part $part")
            && tcl.contains(LocalBuildTemplates.part)
            && !tcl.contains("launch_runs")
            && LocalBuildValidation.routeHasZeroErrors("# of nets with routing errors.......... : 0 :")
            && !LocalBuildValidation.routeHasZeroErrors("# of nets with routing errors.......... : 1 :")
            && ordered
    }

    static func runDockerIntegration() -> Bool {
        let environment = ProcessInfo.processInfo.environment
        guard let vhdlPath = environment["EDGE_LOCAL_TEST_VHDL"],
              let xdcPath = environment["EDGE_LOCAL_TEST_XDC"],
              let outputPath = environment["EDGE_LOCAL_TEST_OUTPUT"],
              let topEntity = environment["EDGE_LOCAL_TEST_TOP"],
              topEntity.range(of: #"^[A-Za-z][A-Za-z0-9_]*$"#, options: .regularExpression) != nil else {
            print("LOCAL DOCKER SELF-TEST requires EDGE_LOCAL_TEST_VHDL, EDGE_LOCAL_TEST_XDC, EDGE_LOCAL_TEST_OUTPUT and EDGE_LOCAL_TEST_TOP")
            return false
        }

        let fileManager = FileManager.default
        let outputURL = URL(fileURLWithPath: outputPath, isDirectory: true)
        let sourceURL = outputURL.appendingPathComponent("source", isDirectory: true)
        let resultURL = outputURL.appendingPathComponent("result", isDirectory: true)
        guard outputURL.path != "/",
              !fileManager.fileExists(atPath: outputURL.path) else {
            print("LOCAL DOCKER SELF-TEST output must be a new directory")
            return false
        }

        do {
            try fileManager.createDirectory(at: sourceURL, withIntermediateDirectories: true)
            try fileManager.createDirectory(at: resultURL, withIntermediateDirectories: true)
            let sourceName = URL(fileURLWithPath: vhdlPath).lastPathComponent
            try fileManager.copyItem(
                at: URL(fileURLWithPath: vhdlPath),
                to: sourceURL.appendingPathComponent(sourceName)
            )
            try fileManager.copyItem(
                at: URL(fileURLWithPath: xdcPath),
                to: sourceURL.appendingPathComponent("constraints.xdc")
            )
            let tcl = LocalBuildTemplates.buildTcl(sourceNames: [sourceName], topEntity: topEntity)
            try tcl.write(
                to: sourceURL.appendingPathComponent("build.tcl"),
                atomically: true,
                encoding: .utf8
            )

            let dockerPath = [
                "/opt/homebrew/bin/docker",
                "/usr/local/bin/docker",
                "/Applications/Docker.app/Contents/Resources/bin/docker"
            ]
                .first { fileManager.isExecutableFile(atPath: $0) }
            guard let dockerPath else { return false }

            let image = environment["EDGE_LOCAL_TEST_DOCKER_IMAGE"]
                ?? LocalBuildTemplates.defaultDockerImage
            let settingsPath = environment["EDGE_LOCAL_TEST_VIVADO_SETTINGS"]
                ?? LocalBuildTemplates.defaultVivadoSettingsPath

            let process = Process()
            let pipe = Pipe()
            process.executableURL = URL(fileURLWithPath: "/usr/bin/caffeinate")
            process.arguments = [
                "-dimsu", dockerPath,
                "run", "--rm", "--pull=never", "--platform", "linux/amd64",
                "--network", "none", "-u", "\(getuid()):\(getgid())",
                "-e", "HOME=/work", "-e", "XILINX_LOCAL_USER_DATA=no",
                "-v", "\(sourceURL.path):/src:ro",
                "-v", "\(resultURL.path):/work:rw",
                image,
                "/bin/bash", "-lc",
                LocalBuildTemplates.vivadoCommand(
                    settingsPath: settingsPath,
                    command: "vivado -mode batch -nolog -nojournal -notrace -source /src/build.tcl"
                )
            ]
            process.standardOutput = pipe
            process.standardError = pipe
            let drain = ProcessOutputDrain(handle: pipe.fileHandleForReading)
            try process.run()
            drain.start { _ in }
            process.waitUntilExit()
            guard drain.waitUntilFinished(timeout: .now() + 3) else { return false }
            let log = drain.snapshot()
            try log.write(
                to: resultURL.appendingPathComponent("build.log"),
                atomically: true,
                encoding: .utf8
            )

            let bitURL = resultURL.appendingPathComponent("\(topEntity).bit")
            let timing = try String(
                contentsOf: resultURL.appendingPathComponent("timing_summary.rpt"),
                encoding: .utf8
            )
            let route = try String(
                contentsOf: resultURL.appendingPathComponent("route_status.rpt"),
                encoding: .utf8
            )
            let passed = process.terminationStatus == 0
                && LocalBuildValidation.resultPassed(
                    log: log,
                    timing: timing,
                    route: route,
                    bitURL: bitURL
                )
            print("LOCAL DOCKER SELF-TEST result=\(resultURL.path)")
            return passed
        } catch {
            print("LOCAL DOCKER SELF-TEST error=\(error.localizedDescription)")
            return false
        }
    }

    static func validateExistingResult() -> Bool {
        let environment = ProcessInfo.processInfo.environment
        guard let resultPath = environment["EDGE_LOCAL_TEST_RESULT"],
              let topEntity = environment["EDGE_LOCAL_TEST_TOP"] else {
            print("LOCAL RESULT SELF-TEST requires EDGE_LOCAL_TEST_RESULT and EDGE_LOCAL_TEST_TOP")
            return false
        }
        let resultURL = URL(fileURLWithPath: resultPath, isDirectory: true)
        do {
            let log = try String(contentsOf: resultURL.appendingPathComponent("build.log"), encoding: .utf8)
            let timing = try String(contentsOf: resultURL.appendingPathComponent("timing_summary.rpt"), encoding: .utf8)
            let route = try String(contentsOf: resultURL.appendingPathComponent("route_status.rpt"), encoding: .utf8)
            let bitURL = resultURL.appendingPathComponent("\(topEntity).bit")
            return LocalBuildValidation.resultPassed(log: log, timing: timing, route: route, bitURL: bitURL)
        } catch {
            print("LOCAL RESULT SELF-TEST error=\(error.localizedDescription)")
            return false
        }
    }
