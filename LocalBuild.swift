            let matchesSearch = query.isEmpty || port.lowercased().contains(query)
            let matchesFilter: Bool
            switch mappingFilter {
            case .all: matchesFilter = true
            case .unmapped: matchesFilter = selected.isEmpty
            case .mapped: matchesFilter = !selected.isEmpty
            case .conflicts: matchesFilter = model.duplicatePins.contains(selected)
            }
            return matchesSearch && matchesFilter
        }
