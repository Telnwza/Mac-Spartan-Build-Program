        case .conflicts: return "Pin ซ้ำ"
        }
    }
}

private struct PinPickerButton: View {
    let port: String
    let selectedPin: String
    let options: [PinOption]
    let owners: [String: String]
    let recentPins: [String]
    let disabled: Bool
    let onSelect: (String) -> Void

    @State private var isPresented = false
    @State private var searchText = ""
    @State private var selectedCategory: PinCategory?
    @State private var availableOnly = true

    private var selectedOption: PinOption? {
        options.first { $0.pin == selectedPin }
    }

    private var filteredOptions: [PinOption] {
        let query = searchText.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        let recentOrder = Dictionary(uniqueKeysWithValues: recentPins.enumerated().map { ($0.element, $0.offset) })
        return options.filter { option in
            let owner = owners[option.pin]
            let matchesAvailability = !availableOnly || owner == nil || owner == port || option.pin == selectedPin
            let matchesCategory = selectedCategory == nil || selectedCategory?.matches(label: option.label) == true
            let matchesSearch = query.isEmpty
                || option.pin.lowercased().contains(query)
                || option.label.lowercased().contains(query)
                || option.category.title.lowercased().contains(query)
            return matchesAvailability && matchesCategory && matchesSearch
        }.sorted { left, right in
            if left.pin == selectedPin { return true }
            if right.pin == selectedPin { return false }
            let leftRecent = recentOrder[left.pin] ?? Int.max
            let rightRecent = recentOrder[right.pin] ?? Int.max
            if leftRecent != rightRecent { return leftRecent < rightRecent }
            if left.category != right.category {
                return PinCategory.allCases.firstIndex(of: left.category) ?? 0
                    < PinCategory.allCases.firstIndex(of: right.category) ?? 0
            }
            return left.label.localizedStandardCompare(right.label) == .orderedAscending
        }
    }

    var body: some View {
        Button {
            isPresented = true
        } label: {
            HStack(spacing: 8) {
                if let selectedOption {
                    Text(selectedOption.label)
                        .lineLimit(1)
                    Spacer()
                    Text(selectedOption.pin)
                        .font(.system(.caption, design: .monospaced).weight(.semibold))
                        .foregroundStyle(.secondary)
                } else {
                    Text("— ยังไม่กำหนด —")
                        .foregroundStyle(.secondary)
                    Spacer()
                }
                Image(systemName: "magnifyingglass")
                    .foregroundStyle(.secondary)
            }
            .frame(maxWidth: .infinity, alignment: .leading)
        }
        .buttonStyle(.bordered)
        .disabled(disabled)
        .popover(isPresented: $isPresented, arrowEdge: .trailing) {
            VStack(spacing: 10) {
                HStack {
                    Image(systemName: "magnifyingglass").foregroundStyle(.secondary)
                    TextField("ค้นหา K12, LED, SW, VGA…", text: $searchText)
                        .textFieldStyle(.plain)
                    if !searchText.isEmpty {
                        Button { searchText = "" } label: {
                            Image(systemName: "xmark.circle.fill")
                        }
                        .buttonStyle(.plain)
                        .foregroundStyle(.secondary)
                    }
                }
                .padding(8)
                .background(Color(nsColor: .controlBackgroundColor), in: RoundedRectangle(cornerRadius: 8))

                HStack {
                    Menu {
                        Button("ทุกหมวด") { selectedCategory = nil }
                        Divider()
                        ForEach(PinCategory.allCases) { category in
                            Button(category.title) { selectedCategory = category }
                        }
                    } label: {
                        Label(selectedCategory?.title ?? "ทุกหมวด", systemImage: "line.3.horizontal.decrease.circle")
                    }
                    Toggle("เฉพาะ Pin ว่าง", isOn: $availableOnly)
                        .toggleStyle(.checkbox)
                    Spacer()
                    Text("\(filteredOptions.count) รายการ")
                        .font(.caption)
                        .foregroundStyle(.secondary)
                }

                Divider()
                ScrollView {
                    LazyVStack(spacing: 4) {
                        Button {
                            onSelect("")
                            isPresented = false
                        } label: {
                            HStack {
                                Image(systemName: selectedPin.isEmpty ? "checkmark.circle.fill" : "circle")
                                Text("ยังไม่กำหนด")
                                Spacer()
                            }
                            .contentShape(Rectangle())
                        }
                        .buttonStyle(.plain)
                        .padding(7)

                        ForEach(filteredOptions) { option in
                            let owner = owners[option.pin]
                            let unavailable = owner != nil && owner != port
                            Button {
                                onSelect(option.pin)
                                isPresented = false
                            } label: {
                                HStack(spacing: 10) {
                                    Image(systemName: option.pin == selectedPin ? "checkmark.circle.fill" : "circle")
                                        .foregroundStyle(option.pin == selectedPin ? Color.accentColor : Color.secondary)
                                    VStack(alignment: .leading, spacing: 2) {
                                        Text(option.label)
                                        Text(option.category.title)
                                            .font(.caption2)
                                            .foregroundStyle(.secondary)
                                    }
                                    Spacer()
                                    if recentPins.contains(option.pin) {
                                        Image(systemName: "clock.arrow.circlepath").foregroundStyle(.secondary)
                                    }
                                    VStack(alignment: .trailing, spacing: 2) {
                                        Text(option.pin)
                                            .font(.system(.body, design: .monospaced).weight(.semibold))
                                        if let owner, owner != port {
                                            Text("ใช้โดย \(owner)")
                                                .font(.caption2)
                                                .foregroundStyle(.orange)
                                        }
                                    }
                                }
                                .contentShape(Rectangle())
                                .padding(7)
                                .background(
                                    option.pin == selectedPin ? Color.accentColor.opacity(0.10) : Color.clear,
                                    in: RoundedRectangle(cornerRadius: 7)
                                )
                            }
                            .buttonStyle(.plain)
                            .disabled(unavailable)
                        }
                    }
                }
            }
            .padding(14)
            .frame(width: 440, height: 500)
        }
    }
}

