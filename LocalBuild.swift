    private func orderedPinOptions(for category: PinCategory) -> [PinOption] {
        pinOptions.filter { category.matches(label: $0.label) }.sorted { left, right in
            let leftRank = resourceRank(left.label, category: category)
            let rightRank = resourceRank(right.label, category: category)
            if leftRank != rightRank { return leftRank < rightRank }
            return left.label.localizedStandardCompare(right.label) == .orderedAscending
        }
    }

    private func resourceRank(_ label: String, category: PinCategory) -> Int {
        let value = label.uppercased()
        func number(after marker: String) -> Int? {
            guard let range = value.range(of: marker) else { return nil }
            let suffix = value[range.upperBound...]
            let digits = suffix.prefix { $0.isNumber }
            return Int(digits)
        }
        switch category {
        case .leds:
            let numbers = [2, 3, 4, 5, 6, 7, 8, 9, 15, 10, 11, 16, 12, 17, 13, 14]
            if let number = number(after: "LED D"),
               let index = numbers.firstIndex(of: number) { return index }
        case .lcd:
            if let index = number(after: "LCD_D") { return index }
            if value.contains("LCD_EN") { return 100 }
            if value.contains("LCD_RS") { return 101 }
        case .sevenSegment:
            let names = ["SEG_A", "SEG_B", "SEG_C", "SEG_D", "SEG_E", "SEG_F", "SEG_G", "SEG_DP"]
            if let index = names.firstIndex(where: value.hasSuffix) { return index }
        case .digitSelect:
            if let index = number(after: "DIGIT") { return index }
        default:
            break
        }
        return 1_000
    }

    private func assignSequentially(
        ports targetPorts: Set<String>,
        category: PinCategory,
        reversed: Bool
    ) {
        guard !targetPorts.isEmpty else { return }
        let orderedPorts = SignalPortGroup.sequentialOrder(Array(targetPorts))
        var candidates = orderedPinOptions(for: category)
        if reversed { candidates.reverse() }

        var nextMapping = selectedPins
        for port in targetPorts { nextMapping[port] = "" }
        let usedPins = Set(
            nextMapping.compactMap { targetPorts.contains($0.key) || $0.value.isEmpty ? nil : $0.value }
        )
        candidates.removeAll { usedPins.contains($0.pin) }

        var assigned = 0
        for (port, option) in zip(orderedPorts, candidates) {
            nextMapping[port] = option.pin
            recentPins = PinMappingStore.recordRecentPin(option.pin)
            assigned += 1
        }
        selectedPins = nextMapping
        let direction = reversed ? "ย้อนลำดับ" : "เรียงลำดับ"
        mappingNotice = "Assign \(category.title) แบบ\(direction) \(assigned)/\(targetPorts.count) signals"
        persistCurrentMapping()
    }

    private func autoMap(targets: Set<String>) {
        guard !targets.isEmpty else {
            mappingNotice = "ไม่มี Signal ที่ต้อง Auto Map"
            return
        }

        var nextMapping = selectedPins
        for port in targets { nextMapping[port] = "" }
        var usedPins = Set(nextMapping.values.filter { !$0.isEmpty })
        let direct = autoMappings(for: Array(targets))

        for port in targets {
            guard let pin = direct[port], !pin.isEmpty, !usedPins.contains(pin) else { continue }
            nextMapping[port] = pin
            usedPins.insert(pin)
        }

        let groups = SignalPortGroup.make(from: ports.filter { targets.contains($0) })
        for group in groups {
            let remaining = Set(group.ports.filter { (nextMapping[$0] ?? "").isEmpty })
            guard !remaining.isEmpty,
                  let category = PinMappingEngine.recommendedCategory(forPort: group.ports[0]) else { continue }
            let candidates = orderedPinOptions(for: category)
                .filter { !usedPins.contains($0.pin) }
            let orderedPorts = SignalPortGroup.sequentialOrder(Array(remaining))
            for (port, option) in zip(orderedPorts, candidates) {
                nextMapping[port] = option.pin
                usedPins.insert(option.pin)
            }
        }

        selectedPins = nextMapping
        let assigned = targets.filter { !(selectedPins[$0] ?? "").isEmpty }.count
        mappingNotice = "Auto Map สำเร็จ \(assigned)/\(targets.count) signals"
        persistCurrentMapping()
    }

    private func autoMappings(for portNames: [String]) -> [String: String] {
        let direct: [String: String] = [
            "clk": "H11", "clock": "H11", "sys_clk": "H11",
            "rst": "J12", "reset": "J12",
            "led": "K12", "led0": "K12", "led1": "M12", "led2": "M14", "led3": "P13",
            "seg_a": "L3", "seg_b": "P4", "seg_c": "P2", "seg_d": "M3",
            "seg_e": "M1", "seg_f": "J4", "seg_g": "K4", "seg_dp": "J2",
            "digit0": "H4", "digit1": "H3", "digit2": "H2", "digit3": "H1"
        ]
        return Dictionary(uniqueKeysWithValues: portNames.map { ($0, direct[$0.lowercased()] ?? "") })
    }

    private func analyzeSources(preferredTop: String?) {
        guard !sourceFiles.isEmpty else {
            entityNames = []
            ports = []
            topEntity = ""
            return
        }
        let paths = sourceFiles.map(\.path)
        let currentMapping = selectedPins
        let previousTopEntity = topEntity
        let previousClockSignal = clockSignal
        let previousClockPeriod = clockPeriod
        let runID = UUID()
        activeAnalysisID = runID
        isAnalyzing = true
        statusText = "กำลังวิเคราะห์ VHDL"
        statusColor = .blue

        Task { [weak self] in
            let analysis = await Task.detached(priority: .userInitiated) {
                VHDLPortParser.analyze(paths: paths, preferredTop: preferredTop)
            }.value
            guard let self, self.activeAnalysisID == runID else { return }
            self.activeAnalysisID = nil
            self.isAnalyzing = false
            self.entityNames = analysis.entityNames
            self.topEntity = analysis.topEntity
            self.ports = analysis.ports
            self.selectedPorts = self.selectedPorts.intersection(analysis.ports)
            let saved = self.profile.flatMap {
                PinMappingStore.lastMapping(profileID: $0.profileID, topEntity: analysis.topEntity)
            }
            let merged = PinMappingEngine.merge(
                ports: analysis.ports,
                current: previousTopEntity.caseInsensitiveCompare(analysis.topEntity) == .orderedSame
                    ? currentMapping
                    : [:],
                saved: saved?.mapping ?? [:],
                automatic: self.autoMappings(for: analysis.ports),
                validPins: Set(self.profile?.pins.keys.map { $0 } ?? [])
            )
            self.selectedPins = merged.mapping
            let savedClock = saved.flatMap { snapshot in
                analysis.ports.first {
                    $0.caseInsensitiveCompare(snapshot.clockSignal) == .orderedSame
                }
            }
            let previousClock = previousTopEntity.caseInsensitiveCompare(analysis.topEntity) == .orderedSame
                ? analysis.ports.first {
                    $0.caseInsensitiveCompare(previousClockSignal) == .orderedSame
                }
                : nil
            self.clockSignal = previousClock ?? savedClock ?? analysis.ports.first {
                ["clk", "clock", "sys_clk"].contains($0.lowercased())
            } ?? analysis.ports.first ?? ""
            self.clockPeriod = previousClock != nil
                ? previousClockPeriod
                : (saved?.clockPeriod ?? "20")
            self.mappingNotice = "รักษา Mapping เดิม \(merged.reusedCount) • Auto \(merged.automaticCount) • ต้องกำหนดเพิ่ม \(merged.unmappedCount)"
            self.statusText = analysis.ports.isEmpty
                ? "ไม่พบ Ports"
                : "พบ \(analysis.ports.count) Ports"
            self.statusColor = analysis.ports.isEmpty ? .red : .blue
            self.appendLog(
                "Top entity: \(analysis.topEntity.isEmpty ? "-" : analysis.topEntity), ports: \(analysis.ports.count)\n"
            )
            self.persistCurrentMapping()
        }
    }

    private func prepareJob() throws -> PreparedJob {
        guard let verifiedImageID else {
            throw NSError(domain: "LocalBuild", code: 1, userInfo: [
                NSLocalizedDescriptionKey: "ยังไม่ได้ยืนยัน Vivado image"
            ])
        }
        let formatter = DateFormatter()
        formatter.locale = Locale(identifier: "en_US_POSIX")
        formatter.dateFormat = "yyyyMMdd_HHmmss"
        let suffix = UUID().uuidString.replacingOccurrences(of: "-", with: "").prefix(6).lowercased()
        let jobID = "local_\(formatter.string(from: Date()))_\(suffix)"
        let jobURL = URL(fileURLWithPath: buildRoot, isDirectory: true)
            .appendingPathComponent(jobID, isDirectory: true)
        let sourceURL = jobURL.appendingPathComponent("source", isDirectory: true)
        let resultURL = jobURL.appendingPathComponent("result", isDirectory: true)
        try FileManager.default.createDirectory(at: sourceURL, withIntermediateDirectories: true)
        try FileManager.default.createDirectory(at: resultURL, withIntermediateDirectories: true)

        var usedNames = Set<String>()
        var sourceNames: [String] = []
        for (index, file) in sourceFiles.enumerated() {
            let ext = file.pathExtension.lowercased() == "vhdl" ? "vhdl" : "vhd"
            var stem = file.deletingPathExtension().lastPathComponent
                .replacingOccurrences(of: #"[^A-Za-z0-9_.-]"#, with: "_", options: .regularExpression)
            if stem.isEmpty { stem = "source" }
            var safeName = "\(stem).\(ext)"
            if usedNames.contains(safeName.lowercased()) {
                safeName = String(format: "%02d_%@.%@", index + 1, stem, ext)
            }
            usedNames.insert(safeName.lowercased())
            try FileManager.default.copyItem(at: file, to: sourceURL.appendingPathComponent(safeName))
            sourceNames.append(safeName)
        }

        let xdcText: String
        if constraintMode == .existingXDC, let selectedXDC {
            xdcText = try String(contentsOf: selectedXDC, encoding: .utf8)
        } else if let period = Double(clockPeriod) {
            xdcText = LocalBuildTemplates.generatedXDC(
                ports: ports,
                selectedPins: selectedPins,
                clockSignal: clockSignal,
                periodNS: period
            )
        } else {
            throw NSError(domain: "LocalBuild", code: 7, userInfo: [NSLocalizedDescriptionKey: "Clock period ไม่ถูกต้อง"])
        }

        let constraintsURL = sourceURL.appendingPathComponent("constraints.xdc")
        try xdcText.write(to: constraintsURL, atomically: true, encoding: .utf8)
        try xdcText.write(to: resultURL.appendingPathComponent("constraints.xdc"), atomically: true, encoding: .utf8)

        let tclText = LocalBuildTemplates.buildTcl(sourceNames: sourceNames, topEntity: topEntity)
        let buildTclURL = sourceURL.appendingPathComponent("build.tcl")
        try tclText.write(to: buildTclURL, atomically: true, encoding: .utf8)
        try tclText.write(to: resultURL.appendingPathComponent("build.tcl"), atomically: true, encoding: .utf8)

        return PreparedJob(
            jobID: jobID,
            topEntity: topEntity,
            imageID: verifiedImageID,
            sourceURL: sourceURL,
            resultURL: resultURL,
            sourceNames: sourceNames,
            buildTclURL: buildTclURL,
            constraintsURL: constraintsURL
        )
    }

    private func runBuild(_ job: PreparedJob) {
        guard let dockerPath else {
            isRunning = false
            fail("ไม่พบ Docker CLI")
            notifyBuild(succeeded: false, top: job.topEntity,
                        message: statusText, destination: job.resultURL)
            return
        }

        let runID = UUID()
        let containerName = "fpga-local-\(job.jobID.replacingOccurrences(of: "_", with: "-"))"
        let process = Process()
        let pipe = Pipe()
        process.executableURL = URL(fileURLWithPath: dockerPath)
        process.arguments = [
            "run", "--rm", "--name", containerName,
            "--pull=never", "--platform", "linux/amd64", "--network", "none",
            "-u", "\(getuid()):\(getgid())",
            "-e", "HOME=/work", "-e", "XILINX_LOCAL_USER_DATA=no",
            "-v", "\(job.sourceURL.path):/src:ro",
            "-v", "\(job.resultURL.path):/work:rw",
            job.imageID,
            "/bin/bash", "-lc",
            LocalBuildTemplates.vivadoCommand(
                settingsPath: configuredVivadoSettingsPath,
                command: "vivado -mode batch -nolog -nojournal -notrace -source /src/build.tcl"
            )
        ]
        process.standardOutput = pipe
        process.standardError = pipe

        let drain = ProcessOutputDrain(handle: pipe.fileHandleForReading)
        currentProcess = process
        activeRunID = runID
        activeContainerName = containerName
        resultFolder = job.resultURL
        completedBitstream = nil
        buildStartedAt = ProcessInfo.processInfo.systemUptime
        buildWasCancelled = false
        isRunning = true
        statusText = "Vivado กำลัง Build บน Mac"
        statusColor = .blue
        appendLog("\n===== Local Build \(job.jobID) =====\n")
        appendLog("Top: \(job.topEntity) • Part: \(LocalBuildTemplates.part)\n")
        appendLog("Image: \(configuredDockerImage) • \(LocalBuildTemplates.dockerPlatform)\n")
        appendLog("Result: \(job.resultURL.path)\n")

        process.terminationHandler = { [weak self] finished in
            DispatchQueue.global(qos: .utility).async {
                let streamClosed = drain.waitUntilFinished(timeout: .now() + 3)
                let captured = drain.snapshot()
                DispatchQueue.main.async {
                    guard let self, self.activeRunID == runID else { return }
                    if self.caffeinateProcess?.isRunning == true {
                        self.caffeinateProcess?.terminate()
                    }
                    self.caffeinateProcess = nil
                    self.currentProcess = nil
                    self.activeRunID = nil
                    self.activeContainerName = nil
                    self.isRunning = false
                    if !streamClosed {
                        self.appendLog("⚠ Log stream ปิดช้ากว่าปกติ\n")
                    }
                    self.finishBuild(job, exitCode: finished.terminationStatus, fullLog: captured)
                }
            }
        }

        do {
            try process.run()
            drain.start { [weak self] text in
                DispatchQueue.main.async {
                    guard let self, self.activeRunID == runID else { return }
                    self.appendLog(text.replacingOccurrences(of: "\r", with: "\n"))
                }
            }
            let keepAwake = Process()
            keepAwake.executableURL = URL(fileURLWithPath: "/usr/bin/caffeinate")
            keepAwake.arguments = ["-dimsu", "-w", String(process.processIdentifier)]
            try keepAwake.run()
            caffeinateProcess = keepAwake
        } catch {
            try? pipe.fileHandleForWriting.close()
            isRunning = false
            currentProcess = nil
            activeRunID = nil
            activeContainerName = nil
            fail("เริ่ม Local Build ไม่สำเร็จ: \(error.localizedDescription)")
            notifyBuild(succeeded: false, top: job.topEntity,
                        message: statusText, destination: job.resultURL)
        }
    }

    private func finishBuild(_ job: PreparedJob, exitCode: Int32, fullLog: String) {
        let logURL = job.resultURL.appendingPathComponent("build.log")
        try? fullLog.write(to: logURL, atomically: true, encoding: .utf8)
        let duration = ProcessInfo.processInfo.systemUptime - (buildStartedAt ?? ProcessInfo.processInfo.systemUptime)
        appendLog(String(format: "\nBuild: %.1f วินาที\n", duration))
        if buildWasCancelled {
            statusText = "ยกเลิก Local Build แล้ว"
            statusColor = .orange
            return
        }
        guard exitCode == 0 else {
            statusText = exitCode == 143 ? "ยกเลิก Local Build แล้ว" : "Local Build ไม่สำเร็จ (รหัส \(exitCode))"
            statusColor = exitCode == 143 ? .orange : .red
            appendLog("\n✗ Build ไม่สำเร็จ เปิด build.log เพื่อตรวจรายละเอียด\n")
            if [125, 126, 127].contains(exitCode) {
                LocalEnvironmentCache.clear(defaults: defaults)
                environmentReady = false
                verifiedImageID = nil
            }
            notifyBuild(succeeded: false, top: job.topEntity,
                        message: statusText, destination: logURL)
            return
        }

        do {
            let bitURL = job.resultURL.appendingPathComponent("\(job.topEntity).bit")
            let timingURL = job.resultURL.appendingPathComponent("timing_summary.rpt")
            let routeURL = job.resultURL.appendingPathComponent("route_status.rpt")
            let bitData = try Data(contentsOf: bitURL)
            let timing = try String(contentsOf: timingURL, encoding: .utf8)
            let route = try String(contentsOf: routeURL, encoding: .utf8)

            guard fullLog.contains("BUILD_COMPLETE:"),
                  !fullLog.contains("ERROR:"),
                  BitstreamInspector.detectedBoard(at: bitURL) == .edgeSpartan7 else {
                throw NSError(domain: "LocalBuild", code: 8, userInfo: [NSLocalizedDescriptionKey: "Bitstream หรือ build log ไม่ผ่านการตรวจสอบ"])
            }
            guard timing.contains("All user specified timing constraints are met") else {
                throw NSError(domain: "LocalBuild", code: 9, userInfo: [NSLocalizedDescriptionKey: "สร้าง .bit ได้ แต่ Timing constraints ไม่ผ่าน"])
            }
            guard LocalBuildValidation.routeHasZeroErrors(route) else {
                throw NSError(domain: "LocalBuild", code: 10, userInfo: [NSLocalizedDescriptionKey: "Route report พบ routing error"])
            }

            let hash = SHA256.hash(data: bitData).map { String(format: "%02x", $0) }.joined()
            try "\(hash)  \(bitURL.lastPathComponent)\n".write(
                to: job.resultURL.appendingPathComponent("SHA256SUMS"),
                atomically: true,
                encoding: .utf8
            )
            let summary = """
            status=PASS
            top=\(job.topEntity)
            part=\(LocalBuildTemplates.part)
            image=\(configuredDockerImage)
            image_id=\(job.imageID)
            vivado_settings=\(configuredVivadoSettingsPath)
            bitstream=\(bitURL.lastPathComponent)
            sha256=\(hash)
            timing=PASS
            routing=PASS
            duration_seconds=\(String(format: "%.1f", duration))
            """
            try summary.write(
                to: job.resultURL.appendingPathComponent("local-build-summary.txt"),
                atomically: true,
                encoding: .utf8
            )

            completedBitstream = bitURL
            statusText = "Local Build สำเร็จ พร้อม Program"
            statusColor = .green
            appendLog("\n✓ Synthesis, placement และ routing สำเร็จ\n")
            appendLog("✓ Timing constraints ผ่าน\n")
            appendLog("✓ SHA-256: \(hash)\n")
            appendLog("ไฟล์พร้อมใช้: \(bitURL.path)\n")
            notifyBuild(succeeded: true, top: job.topEntity,
                        message: String(format: "Timing และ Routing ผ่าน · ใช้เวลา %.1f วินาที", duration),
                        destination: job.resultURL)
        } catch {
            fail(error.localizedDescription)
            notifyBuild(succeeded: false, top: job.topEntity,
                        message: error.localizedDescription, destination: logURL)
        }
    }

    private func runTool(
        executable: String,
        arguments: [String],
        errorMessage: String
    ) async throws -> String {
        let result: (Int32, String) = await withCheckedContinuation { continuation in
            let process = Process()
            let pipe = Pipe()
            let drain = ProcessOutputDrain(handle: pipe.fileHandleForReading)
            process.executableURL = URL(fileURLWithPath: executable)
            process.arguments = arguments
            process.standardOutput = pipe
            process.standardError = pipe
            currentProcess = process

            process.terminationHandler = { [weak self] finished in
                DispatchQueue.global(qos: .utility).async {
                    let closed = drain.waitUntilFinished(timeout: .now() + 2)
                    let captured = drain.snapshot()
                    DispatchQueue.main.async {
                        if self?.currentProcess === finished { self?.currentProcess = nil }
                        continuation.resume(returning: (closed ? finished.terminationStatus : -1, captured))
                    }
                }
            }
            do {
                try process.run()
                drain.start { [weak self] text in
                    DispatchQueue.main.async {
                        guard self?.currentProcess === process else { return }
                        self?.appendLog(text.replacingOccurrences(of: "\r", with: ""))
                    }
                }
            } catch {
                try? pipe.fileHandleForWriting.close()
                currentProcess = nil
                continuation.resume(returning: (-1, error.localizedDescription))
            }
        }
        try Task.checkCancellation()
        guard result.0 == 0 else {
            throw NSError(domain: "LocalBuild", code: Int(result.0), userInfo: [
                NSLocalizedDescriptionKey: errorMessage
            ])
        }
        return result.1
    }

    private func appendLog(_ text: String) {
        uiLog.append(text)
    }

    private func fail(_ message: String) {
        statusText = message
        statusColor = .red
        appendLog("✗ \(message)\n")
    }
