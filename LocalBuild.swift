    var duplicatePins: Set<String> {
        let selected = selectedPins.values.filter { !$0.isEmpty }
        let counts = Dictionary(grouping: selected, by: { $0 }).mapValues(\.count)
        return Set(counts.filter { $0.value > 1 }.map(\.key))
    }

    var unmappedPortCount: Int {
        ports.filter { (selectedPins[$0] ?? "").isEmpty }.count
    }

    var canBuild: Bool {
        guard !isRunning, !isAnalyzing, !sourceFiles.isEmpty,
              topEntity.range(of: #"^[A-Za-z][A-Za-z0-9_]*$"#, options: .regularExpression) != nil else {
            return false
        }
        switch constraintMode {
        case .existingXDC:
            guard let selectedXDC else { return false }
            return selectedXDC.pathExtension.lowercased() == "xdc"
                && FileManager.default.fileExists(atPath: selectedXDC.path)
        case .guided:
            guard !ports.isEmpty, unmappedPortCount == 0, duplicatePins.isEmpty,
                  ports.contains(clockSignal), let period = Double(clockPeriod) else { return false }
            return period >= 0.1 && period <= 1_000_000
        }
    }

    var freeSpaceText: String {
        guard let bytes = try? freeBytes(at: buildRoot) else { return "ไม่ทราบพื้นที่ว่าง" }
        return ByteCountFormatter.string(fromByteCount: Int64(bytes), countStyle: .file)
    }

    var minimumFreeBytes: UInt64? {
        guard let value = Double(minimumFreeGiB), value >= 1, value <= 1_000 else { return nil }
        return UInt64(value * 1_024 * 1_024 * 1_024)
    }

